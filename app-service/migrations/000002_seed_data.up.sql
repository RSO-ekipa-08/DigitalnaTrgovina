-- Vstavljanje vzorčnih prenosov
INSERT INTO downloads (
    user_id,
    application_id,
    ip_address,
    success,
    error_message
)
SELECT 
    md5(random()::text)::uuid as user_id,
    id as application_id,
    '192.168.' || (random() * 255)::int || '.' || (random() * 255)::int as ip_address,
    CASE WHEN random() > 0.1 THEN true ELSE false END as success,
    CASE WHEN random() > 0.1 THEN NULL ELSE 'Network connection error' END as error_message
FROM applications
CROSS JOIN generate_series(1, 5)
ORDER BY random()
LIMIT 100;
